import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { launchBrowser, baseURL, ready } from './browser.mjs';
const uk=JSON.parse(await readFile('content/locales/uk.json','utf8'));
const slide=uk.slides.find(slide=>slide.id==='s01');
const browser=await launchBrowser();
const current=page=>page.locator('.scaled-slide .presentation-slide-layer:last-child .v2-s01');
try {
 const page=await browser.newPage({viewport:{width:1920,height:1080}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto(`${baseURL}/uk/vision#s01`);await ready(page);
 await current(page).waitFor();
 await current(page).evaluate(el=>Promise.all(el.getAnimations({subtree:true}).filter(a=>a.effect.getTiming().iterations!==Infinity).map(a=>a.finished)));
 assert.equal(await current(page).locator('h2 em').innerText(),'можливості.');
 assert.equal(await current(page).locator('.v2-cover-copy > p').innerText(),slide.lead);
 assert.equal(await current(page).locator('.v2-growth').getAttribute('aria-label'),slide.diagramAlt);
 assert.deepEqual(await current(page).locator('.growth-node').evaluateAll(nodes=>nodes.map(node=>node.getAttribute('aria-label'))),slide.stages);
 if(uk.status==='draft') assert((await page.locator('.translation-notice').innerText()).includes(`${uk.slides.length} із 17`));
 if(uk.status==='draft') assert(!(await page.locator('.translation-notice').innerText()).includes(uk.ui.slideFallback));
 assert.equal(await page.locator('.presentation-slide-layer:last-child').getAttribute('lang'),'uk');
 const bounds=await current(page).evaluate(el=>{
  const headline=el.querySelector('h2'), styles=getComputedStyle(headline);
  const canvas=el.getBoundingClientRect();
  return {lines:headline.offsetHeight/parseFloat(styles.lineHeight), fits:[...el.querySelectorAll('.v2-cover-copy,.v2-cover-signoff')].every(node=>{const r=node.getBoundingClientRect();return r.right<=canvas.right && r.bottom<=canvas.bottom;})};
 });
 assert(bounds.lines<2.2 && bounds.lines>1.8,`Expected two headline lines, got ${bounds.lines}`);assert(bounds.fits);
 const nodes=current(page).locator('.growth-node');
 await nodes.nth(2).locator('.growth-node-surface').hover();await page.waitForTimeout(240);
 assert.equal(await nodes.nth(2).locator('.growth-node-label').evaluate(el=>getComputedStyle(el).opacity),'1');
 assert.equal(await nodes.nth(2).locator('.growth-node-label').textContent(),'Зв’язки');
 await page.mouse.move(0,0);await nodes.nth(3).focus();
 assert(await nodes.nth(3).evaluate(el=>el.matches(':focus-visible')));
 await page.keyboard.press('ArrowRight');
 assert.equal(await current(page).getAttribute('data-slide'),'s01');
 await page.emulateMedia({reducedMotion:'reduce'});
 assert.equal(await nodes.last().locator('.growth-node-reveal').evaluate(el=>getComputedStyle(el).opacity),'1');
 await page.mouse.click(5,5);
 await page.screenshot({path:join(tmpdir(),'detelgy-uk-slide01-viewer.png'),fullPage:true});
 await page.emulateMedia({media:'print',reducedMotion:'reduce'});
 const printed=page.locator('.print-only .v2-s01');
 assert.equal(await printed.locator('.growth-trajectory').evaluate(el=>getComputedStyle(el).strokeDasharray),'none');
 assert.equal(await printed.locator('.growth-node-reveal').last().evaluate(el=>getComputedStyle(el).opacity),'1');
 await printed.screenshot({path:join(tmpdir(),'detelgy-uk-slide01-1920.png')});
 await page.emulateMedia({media:'screen'});
 await page.getByRole('button',{name:uk.ui.present,exact:true}).first().click();
 await page.waitForFunction(()=>document.querySelector('.studio').dataset.playbackBusy==='false');
 assert.equal(await current(page).locator('h2 em').innerText(),'можливості.');
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:uk.ui.next,exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.scaled-slide .presentation-slide-layer:last-child .slide')?.dataset.slide==='s02');
 if(uk.status==='draft') assert((await page.locator('.translation-notice').innerText()).includes(uk.slides.some(slide=>slide.id==='s02')?uk.ui.translatedSlide:uk.ui.slideFallback));
 await page.goto(`${baseURL}/en/vision#s01`);await ready(page);
 assert.equal(await current(page).locator('h2 em').innerText(),'opportunity.');
 assert.deepEqual(await current(page).locator('.growth-node').evaluateAll(nodes=>nodes.map(node=>node.getAttribute('aria-label'))),['Start','Profile','Connections','Opportunities','Growth']);
 const phone=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce'});
 await phone.goto(`${baseURL}/uk/vision#s01`);await ready(phone);
 assert(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 assert.equal(await phone.locator('.reading-content,.mobile-reading-toggle').count(),0);
 await phone.screenshot({path:join(tmpdir(),'detelgy-uk-slide01-mobile.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('Ukrainian cover passed: two-line headline, localized milestones/ARIA, hover/focus, entrance/reduced motion, static print, Present Mode, mobile, English preservation and next-slide translation status.');
} finally {await browser.close();}
