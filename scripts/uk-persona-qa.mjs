import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {launchBrowser,baseURL,ready} from './browser.mjs';
const uk=JSON.parse(await readFile('content/locales/uk.json','utf8'));
const content=uk.slides.find(slide=>slide.id==='s04');
const browser=await launchBrowser();
const current=page=>page.locator('.scaled-slide .presentation-slide-layer:last-child .story-s04');
try {
 const page=await browser.newPage({viewport:{width:1920,height:1080}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto(`${baseURL}/uk/vision#s04`);await ready(page);await current(page).waitFor();
 const slide=current(page);
 const delays=await slide.evaluate(el=>['.story-portrait','.story-portrait > div','.story-title',...Array.from({length:3},(_,i)=>`[data-tension="${i}"]`)].map(selector=>el.querySelector(selector).getAnimations()[0]?.effect.getTiming().delay));
 assert.deepEqual(delays,[0,450,800,1150,1330,1510]);
 await slide.evaluate(el=>Promise.all(el.getAnimations({subtree:true}).filter(a=>a.effect.getTiming().iterations!==Infinity).map(a=>a.finished)));
 assert.equal(await slide.locator('.story-portrait strong').innerText(),content.persona.name);
 assert.equal(await slide.locator('.story-portrait .persona-profession').innerText(),content.persona.profession);
 assert.deepEqual(await slide.locator('.persona-tensions h3').allTextContents(),content.displayItems.map(item=>item.body));
 if(uk.status==='draft') assert((await page.locator('.translation-notice').innerText()).includes(`${uk.slides.length} із 17`));
 assert(!(await page.content()).includes(content.note.slice(0,80)));
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.screenshot({path:join(tmpdir(),'detelgy-uk-slide04-viewer.png'),fullPage:true});
 await page.emulateMedia({media:'print'});
 const printed=page.locator('.print-only .story-s04');
 await printed.screenshot({path:join(tmpdir(),'detelgy-uk-slide04-1920.png')});
 const geometry=await printed.evaluate(el=>{
  const title=el.querySelector('.story-title h2');
  const canvas=el.getBoundingClientRect();
  return {lines:title.offsetHeight/parseFloat(getComputedStyle(title).lineHeight),fits:[...el.querySelectorAll('.story-portrait strong,.persona-tensions h3')].every(node=>{const r=node.getBoundingClientRect();return r.right<=canvas.right && r.bottom<=canvas.bottom;})};
 });
 assert(geometry.lines<=2.2,`Headline wrapped into ${geometry.lines} lines`);assert(geometry.fits);
 assert.equal((await printed.locator('.slide-folio').innerText()).replace(/\s/g,''),'04/17');
 assert.equal(await printed.locator('.persona-tensions section').count(),3);
 await page.emulateMedia({media:'screen'});
 await page.getByRole('button',{name:uk.ui.present,exact:true}).first().click();
 await page.waitForFunction(()=>document.querySelector('.studio').dataset.playbackBusy==='false');
 assert.equal(await slide.locator('.persona-tensions section').last().evaluate(el=>getComputedStyle(el).opacity),'1');
 await page.keyboard.press('Escape');
 const phone=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce'});
 await phone.goto(`${baseURL}/uk/vision#s04`);await ready(phone);
 assert(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 await phone.screenshot({path:join(tmpdir(),'detelgy-uk-slide04-mobile.png'),fullPage:true});
 await page.goto(`${baseURL}/en/vision#s04`);await ready(page);
 assert.equal(await current(page).locator('.story-portrait strong').innerText(),'Dmytro · 41');
 assert.equal(await current(page).locator('.persona-tensions h3').first().innerText(),'12 years in practice');
 assert.deepEqual(errors,[]);
 console.log('Ukrainian Slide 04 passed: persona details, headline fit, three dimensions, ordered entrance, reduced motion, static print, Present Mode, mobile and unchanged English.');
} finally {await browser.close();}
