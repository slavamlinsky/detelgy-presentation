import {launchBrowser,baseURL,ready} from './browser.mjs';
import assert from 'node:assert/strict';
const browser=await launchBrowser();
try{
 const page=await browser.newPage({viewport:{width:1920,height:1080},reducedMotion:'no-preference'});
 await page.goto(`${baseURL}/en/vision/print`);await ready(page);
 const footers=await page.locator('.slide-footer').allTextContents();
 assert.equal(footers.length,14);
 footers.forEach((text,i)=>assert.equal(text.replace(/\s/g,''),`${String(i+1).padStart(2,'0')}/14`));
 await page.locator('[data-slide="s02"]').screenshot({path:'qa/v2/s02.png'});
 await page.setViewportSize({width:1366,height:768});
 await page.goto(`${baseURL}/en/vision#s02`);await ready(page);
 const slide=page.locator('.scaled-slide .v2-s02');await slide.waitFor();
 await slide.evaluate(el=>Promise.all(el.getAnimations({subtree:true}).filter(a=>a.effect.getTiming().iterations!==Infinity).map(a=>a.finished)));
 assert.equal(await slide.locator('.fragment-expert text').textContent(),'Polygraph Examiner');
 await page.getByRole('button',{name:'Speaker notes',exact:true}).click();
 const notes=page.locator('.notes-panel');
 assert.match(await notes.textContent(),/hypothesis/);
 assert.match(await notes.textContent(),/Existing networks already provide value/);
 assert.match(await notes.textContent(),/expert discovery and market learning/);
 assert.equal(await notes.locator('a').count(),2);
 await page.getByRole('button',{name:'Speaker notes',exact:true}).click();
 assert.equal(await slide.locator('.fragment-meridian').evaluateAll(els=>els.flatMap(el=>el.getAnimations()).length),0);
 const globe=slide.locator('.fragment-unit').first();
 const timing=await globe.evaluate(el=>el.getAnimations()[0].effect.getTiming());
 assert.equal(timing.duration,480000);
 assert.equal(timing.iterations,Infinity);
 assert.equal(await slide.locator('.fragment-globe').getAttribute('opacity'),'0.20');
 const details=slide.locator('.fragment-detail');
 assert.equal(await details.count(),4);
 assert((await details.evaluateAll(es=>es.map(e=>getComputedStyle(e).opacity))).every(v=>v==='0'));
 await page.screenshot({path:'qa/v2/s02-laptop.png'});
 for(let i=0;i<4;i++){
  const node=slide.locator('.fragment-node').nth(i);
  const box=await node.locator('.fragment-surface').boundingBox();await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.waitForTimeout(220);
  assert((await slide.locator('.fragment-unit').evaluateAll(els=>els.map(el=>getComputedStyle(el).animationPlayState))).every(s=>s==='paused'));
  assert.equal(await details.nth(i).evaluate(e=>getComputedStyle(e).opacity),'1');
  assert.equal(await slide.locator('.fragment-link').nth(i).evaluate(e=>getComputedStyle(e).stroke),'rgb(111, 154, 188)');
  if(i===1)await page.screenshot({path:'qa/v2/s02-clients-hover.png'});
 }
 await page.mouse.move(0,0);await page.keyboard.press('Tab');await slide.locator('.fragment-node').nth(0).focus();await page.waitForTimeout(220);
 assert.equal(await details.nth(0).evaluate(e=>getComputedStyle(e).opacity),'1');
 await slide.locator('.fragment-node').nth(0).evaluate(e=>e.blur());
 const center=slide.locator('.fragment-expert');await center.locator('circle').nth(1).hover();await page.waitForTimeout(220);
 assert((await slide.locator('.fragment-link').evaluateAll(es=>es.map(e=>getComputedStyle(e).stroke))).every(v=>v==='rgb(140, 171, 195)'));
 assert((await details.evaluateAll(es=>es.map(e=>getComputedStyle(e).opacity))).every(v=>v==='0'));
 await page.screenshot({path:'qa/v2/s02-center-hover.png'});
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.waitForFunction(()=>document.querySelector('.scaled-slide .v2-s02').getAnimations({subtree:true}).length===0);
 await page.emulateMedia({media:'print'});
 const printed=page.locator('.print-only .v2-s02');
 assert.equal(await printed.locator('.fragment-node-reveal').first().evaluate(e=>getComputedStyle(e).opacity),'1');
 assert.equal(await printed.locator('.fragment-detail').first().evaluate(e=>getComputedStyle(e).display),'none');
 await page.emulateMedia({media:'screen',reducedMotion:'no-preference'});
 await page.evaluate(()=>location.hash='s03');
 await page.waitForFunction(()=>!document.querySelector('.scaled-slide .fragment-scene'));
 assert.equal(await page.locator('.fragment-unit').evaluateAll(els=>els.flatMap(el=>el.getAnimations()).length),0);
 console.log('Passed: four hover details, related links, keyboard focus, center emphasis, reduced motion, static print.');
}finally{await browser.close();}
