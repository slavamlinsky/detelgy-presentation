import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { launchBrowser, baseURL, ready } from './browser.mjs';
const uk=JSON.parse(await readFile('content/locales/uk.json','utf8'));
const translated=uk.slides.find(slide=>slide.id==='s02');
const browser=await launchBrowser();
const current=page=>page.locator('.scaled-slide .presentation-slide-layer:last-child .v2-s02');
try {
 const page=await browser.newPage({viewport:{width:1920,height:1080},reducedMotion:'reduce'});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto(`${baseURL}/uk/vision#s02`);await ready(page);await current(page).waitFor();
 assert.equal(await current(page).locator('.fragment-expert text').textContent(),'Поліграфолог');
 assert.equal(await current(page).locator('.v2-fragment-copy p').innerText(),translated.lead);
 assert.deepEqual(await current(page).locator('.fragment-node-reveal > text:first-of-type').allTextContents(),translated.displayItems.map(item=>item.title));
 if(uk.status==='draft') assert((await page.locator('.translation-notice').innerText()).includes(`${uk.slides.length} із 17`));
 assert(!(await page.content()).includes(translated.note.slice(0,80)));
 const headingLines=await current(page).locator('h2').evaluate(el=>el.offsetHeight/parseFloat(getComputedStyle(el).lineHeight));
 await page.screenshot({path:join(tmpdir(),'detelgy-uk-slide02-viewer.png'),fullPage:true});
 await page.emulateMedia({media:'print',reducedMotion:'reduce'});
 const printed=page.locator('.print-only .v2-s02');
 await printed.screenshot({path:join(tmpdir(),'detelgy-uk-slide02-1920.png')});
 assert(headingLines<=2.2,`Expected a two-line headline, got ${headingLines}`);
 assert.equal(await printed.locator('.fragment-detail').first().evaluate(el=>getComputedStyle(el).display),'none');
 assert.equal(await printed.locator('.fragment-node-reveal').last().evaluate(el=>getComputedStyle(el).opacity),'1');
 await page.emulateMedia({media:'screen',reducedMotion:'no-preference'});
 await current(page).evaluate(el=>Promise.all(el.getAnimations({subtree:true}).filter(a=>a.effect.getTiming().iterations!==Infinity).map(a=>a.finished)));
 assert.equal(await current(page).locator('.fragment-unit').first().evaluate(el=>el.getAnimations()[0].effect.getTiming().duration),480000);
 const nodes=current(page).locator('.fragment-node');
 for (let i=0;i<4;i++) {
  const bounds=await nodes.nth(i).locator('.fragment-surface').boundingBox();
  await page.mouse.move(bounds.x+bounds.width/2,bounds.y+bounds.height/2);await page.waitForTimeout(240);
  assert.equal(await nodes.nth(i).locator('.fragment-detail').textContent(),translated.displayItems[i].body);
  assert.equal(await nodes.nth(i).locator('.fragment-detail').evaluate(el=>getComputedStyle(el).opacity),'1');
  assert((await current(page).locator('.fragment-unit').evaluateAll(els=>els.map(el=>getComputedStyle(el).animationPlayState))).every(state=>state==='paused'));
  const detail=await nodes.nth(i).locator('.fragment-detail').boundingBox();
  const canvas=await current(page).boundingBox();
  assert(detail.x>=canvas.x && detail.x+detail.width<=canvas.x+canvas.width,'Hover detail exceeds slide');
 }
 await page.mouse.move(0,0);await page.keyboard.press('Tab');await nodes.first().focus();await page.waitForTimeout(240);
 assert.equal(await nodes.first().locator('.fragment-detail').evaluate(el=>getComputedStyle(el).opacity),'1');
 await page.mouse.click(5,5);
 const center=current(page).locator('.fragment-expert');await center.locator('circle').nth(1).hover();await page.waitForTimeout(240);
 assert((await current(page).locator('.fragment-link').evaluateAll(els=>els.map(el=>getComputedStyle(el).stroke))).every(stroke=>stroke==='rgb(140, 171, 195)'));
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.getByRole('button',{name:uk.ui.present,exact:true}).first().click();
 await page.waitForFunction(()=>document.querySelector('.studio').dataset.playbackBusy==='false');
 assert.equal(await current(page).locator('.fragment-expert text').textContent(),'Поліграфолог');
 await page.keyboard.press('Escape');
 const phone=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce'});
 await phone.goto(`${baseURL}/uk/vision#s02`);await ready(phone);
 assert(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 await phone.screenshot({path:join(tmpdir(),'detelgy-uk-slide02-mobile.png'),fullPage:true});
 await page.goto(`${baseURL}/en/vision#s02`);await ready(page);
 assert.equal(await current(page).locator('.fragment-expert text').textContent(),'Polygraph Examiner');
 assert.deepEqual(await current(page).locator('.fragment-node-reveal > text:first-of-type').allTextContents(),['Visibility','Clients','Peers','Learning']);
 assert.deepEqual(errors,[]);
 console.log('Ukrainian Slide 02 passed: heading, four categories, hover/focus, orbit pause/timing, center emphasis, mobile, static print, Present Mode and English preservation.');
} finally {await browser.close();}
